/** Известные люди в названиях наград и учреждений: основы фамилий, сами по себе ничего не значат, нужен контекст. */
const RE_HISTORICAL = /^(?:невск|нахимов|суворов|кутузов|ушаков|жуков|ленин|сталин|пушкин|ломоносов|менделеев|пирогов)(?:а|у|ым|ом|е|ого|ому|им|ий)?$/

const STOP_WORDS: ReadonlySet<string> = (() => {
  const out = new Set<string>()
  for (const s of NOUN_STEMS) {
    for (const e of NOUN_ENDINGS) out.add(`${s}${e}`.replace(/ё/g, 'е'))
  }
  for (const s of ADJECTIVE_STEMS) {
    for (const e of ADJECTIVE_ENDINGS) out.add(`${s}${e}`.replace(/ё/g, 'е'))
  }
  for (const w of FUNCTION_WORDS) out.add(w.replace(/ё/g, 'е'))
  return out
})()

/** Слово из служебного списка: фамилией считать нельзя даже рядом с инициалами. */
export function isStopWord(word: string): boolean {
  const w = word.toLowerCase().replace(/ё/g, 'е')
  if (STOP_WORDS.has(w)) return true
  // Составные через дефис: «Волго-Вятского», «Северо-Западного».
  return w.includes('-') && w.split('-').every(p => STOP_WORDS.has(p))
}

/** Фамилия из названий наград и учреждений. Сама по себе ничего не решает: у живых людей такие фамилии тоже есть. */
export function isHistoricalName(word: string): boolean {
  return RE_HISTORICAL.test(word.toLowerCase().replace(/ё/g, 'е'))
}

/** Пары букв с точками, которые выглядят как инициалы, но ими не являются: «Т.Е.», «И.О.», «Р.Ф.». */
const NOT_INITIALS: ReadonlySet<string> = new Set(['ТЕ', 'ТК', 'ИО', 'ТД', 'ТП', 'ЮЛ', 'ФЛ', 'ИП', 'ДР', 'РФ', 'АО', 'НЭ', 'ЧЛ'])

export function isNotInitials(pair: string): boolean {
  return NOT_INITIALS.has(pair)
}

/** Сокращения из двух заглавных букв: они не инициалы без точек («Законов РФ», «Сидоров АО»). */
const ABBREVIATIONS: ReadonlySet<string> = new Set(['РФ', 'АО', 'ГК', 'НК', 'УК', 'ТК', 'СК', 'ЖК', 'ЗК', 'БК', 'ИП', 'МВ', 'ТО', 'СЗ', 'КС', 'ВС', 'ЕС', 'ИТ', 'ПО', 'ТЗ', 'РЕ'])

export function isAbbreviation(word: string): boolean {
  return ABBREVIATIONS.has(word)
}
