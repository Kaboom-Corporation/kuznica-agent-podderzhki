/**
 * Общие типы маскировки ПДн перед отправкой текста во внешнюю модель.
 * Распознавание (document-detector.ts, contacts.ts) отдаёт PiiSpan[],
 * хранилище меток (vault.ts) превращает их в метки и обратно.
 */

/** Что за ПДн нашли. От вида зависит префикс метки. */
export type PiiKind =
  | 'employee' // сотрудник: Сотрудник_N / Сотрудница_N
  | 'client' // клиент-физлицо или ИП: Клиент_N
  | 'contact' // контактное лицо клиента: Контакт_N
  | 'student' // ученик: Ученик_N
  | 'parent' // родитель: Родитель_N
  | 'phone' // Телефон_N
  | 'email' // Почта_N
  | 'messenger' // ник/ссылка мессенджера: Мессенджер_N
  | 'mention' // неоднозначное упоминание имени: Имя_N, возвращается тем же словом
  // Виды ниже находит детектор документов (document-detector.ts).
  | 'person' // человек из документа: Человек_N
  | 'address' // адрес: Адрес_N
  | 'passport' // Паспорт_N
  | 'inn' // ИНН физлица: ИННФЛ_N
  | 'ogrnip' // ОГРНИП_N
  | 'snils' // СНИЛС_N
  | 'birthdate' // дата рождения: ДатаРождения_N
  | 'license' // водительское удостоверение: Водительское_N
  | 'card' // банковская карта: Карта_N
  | 'account' // банковский счёт: Счёт_N
  | 'vehicle' // номер автомобиля или VIN: Автомобиль_N

export type PiiGender = 'm' | 'f'

/** Человек из словаря (для режима «по словарю»: имена, известные вызывающему). */
export interface PiiPerson {
  /** Стабильный ключ: `${kind}:${id}` — одна метка на человека. */
  key: string
  kind: Extract<PiiKind, 'employee' | 'client' | 'contact' | 'student' | 'parent'>
  /** Полное имя («Юлия Петрова»). По нему ищем упоминания. */
  fullName: string
  gender?: PiiGender
  /** Прятать только имя целиком, отдельные слова — нет (бренды, названия с городом). */
  wholeNameOnly?: boolean
}

/** Найденный в тексте кусок ПДн: полуинтервал [start, end) в исходной строке. */
export interface PiiSpan {
  start: number
  end: number
  kind: PiiKind
  /**
   * Ключ для метки. Для людей — PiiPerson.key; для телефона/почты — нормализованное значение
   * (цифры номера, почта в нижнем регистре); для mention — нормализованное слово.
   */
  key: string
  /** Каноническое значение: для людей — fullName, для контактов — исходный текст. */
  canonical: string
  gender?: PiiGender
  /** Форма для возврата с учётом падежа метки: окончание «у» из «Человеку_1» → «Иванову И.И.». Без него — canonical. */
  render?: (labelEnding: string) => string
}
